/**
 * assemble.mjs — сборка всех страниц сайта из данных. Без файловой системы:
 * всё внешнее приходит аргументами.
 */

import { страницаСущности, страница, заголовокРаздела, форма, строкаОплаты, прошло } from './render.mjs';
import { собратьБлок, собратьЭлемент, времяЗанятий, НАПОЛНЕНИЯ, СТРАНИЧНЫЕ, ВИДЫ } from './blocks.mjs';

export const подставить = (t, з) => String(t).replace(/\{([^}]+)\}/g, (_, k) => з[k] ?? '');

export function основыИзображений({ site, catalog }) {
  return [...new Set([
    ...[...catalog.courses, ...catalog.events, ...catalog.camp.смены].map(x => x.изображение),
    ...(site.галерея || []).map(к => к.основа),
    ...catalog.team.map(т => т.фото),
  ].filter(Boolean))];
}

/** Типографика применяется к тексту страницы; теги и атрибуты не затрагиваются. */
export function типографика(html, правила) {
  if (!правила || !правила.length) return html;
  const готовые = правила.map(п => ({ re: new RegExp(п.найти, 'g'), на: п.заменить }));
  return html.replace(/(<[^>]*>)|([^<]+)/g, (всё, тег, текст) => {
    if (тег) return тег;
    let t = текст;
    for (const п of готовые) t = t.replace(п.re, п.на);
    return t;
  });
}

export function сверитьТипы(types, structure) {
  const беды = [];
  const без$ = o => Object.keys(o).filter(k => !k.startsWith('$'));
  const сверить = (что, объявлено, реализовано) => {
    объявлено.filter(t => !реализовано.includes(t))
      .forEach(t => беды.push(`${что}: «${t}» объявлен в types.json, но не реализован`));
    реализовано.filter(t => !объявлено.includes(t))
      .forEach(t => беды.push(`${что}: «${t}» реализован, но не объявлен в types.json`));
  };

  сверить('наполнение', без$(types.наполнения),
          [...Object.keys(НАПОЛНЕНИЯ), ...Object.keys(СТРАНИЧНЫЕ)]);

  const виды = String((types.наполнения.карточки.поля || {}).вид || '')
    .split('|').map(x => x.trim()).filter(Boolean);
  сверить('вид карточки', виды, Object.keys(ВИДЫ));

  const сущности = без$(types.сущности);
  сверить('сущность', сущности, без$(structure.templates));
  for (const вид of сущности) {
    const о = types.сущности[вид], ш = structure.templates[вид];
    if (ш && о.папка !== ш.папка)
      беды.push(`сущность «${вид}»: папка в словаре «${о.папка}», в шаблоне «${ш.папка}»`);
    if (!виды.includes(вид))
      беды.push(`сущность «${вид}»: нет одноимённого вида карточки`);
  }

  return беды;
}

export function собратьСайт({ данные, размеры = {}, текст = () => '', сегодня }) {
  const { site, catalog, structure, types } = данные;
  const структура = structure;
  const { courses, events, camp, prices, blog } = catalog;
  const TODAY = сегодня;
  const замечания = [];

  if (types) {
    замечания.push(...сверитьТипы(types, structure));
  }

  const читать = отн => {
    const s = текст(отн);
    if (s == null) { замечания.push(`нет файла ${отн}`); return ''; }
    return String(s).replace(/\n$/, '');
  };

  const контекст = (сущность, значения, путь) => ({
    depth: путь.split('/').length - 1, up: '../'.repeat(путь.split('/').length - 1),
    путь, размеры, значения,
    прошло: x => прошло((x.дата || x.даты || {}).по || x, TODAY),
    времяЗанятий, оплата: c => строкаОплаты(prices[c.тариф]),
    текст: путь => читать(подставить(путь, значения)),
    таблица: б => {
      if (б.источник === 'prices') {
        const строки = Object.values(prices).filter(т => т && т.вТаблице)
          .sort((a, b) => a.порядок - b.порядок)
          .map(т => [т.вТаблице,
                     т.пробное ? `${т.пробное} ₽` : '—',
                     т.разовое ? `${т.разовое} ₽` : '—',
                     т.пакеты.map(п => `${п.вТаблице} — ${п.цена} ₽`).join(', ')]);
        return { колонки: ['Направление', 'Пробное', 'Разовое', 'Абонемент / модуль'], строки,
                 ширины: ['33.3333%', '16.6667%', '16.6667%', '33.3333%'],
                 шапкаБезScope: true, примечание: prices.$примечание };
      }
      if (б.источник === 'camp.распорядок')
        return { колонки: ['Время', 'Что происходит'], строки: camp.распорядок.строки,
                 ширины: ['22%', '78%'], примечание: camp.распорядок.примечание };
      throw new Error(`неизвестный источник таблицы: ${б.источник}`);
    },
  });

  const собрано = [];

  const собратьСущности = (вид, список, значенияFn) => {
    const шаблон = structure.templates[вид];
    for (const сущность of список) {
      const значения = значенияFn(сущность);
      const путь = `${шаблон.папка}/${сущность.id}/index.html`;
      const ctx = контекст(сущность, значения, путь);
      const блоки = шаблон.блоки.map(б => собратьБлок({ ...б, текст: б.текст && подставить(б.текст, значения) }, ctx));
      собрано.push([путь, страницаСущности({ вид, сущность, шаблон, site, структура, ctx, блоки })]);
    }
  };

  собратьСущности('курс', courses, c => ({ ...c, дата: '' }));
  собратьСущности('событие', events, e => ({ ...e, дата: e.дата.подпись }));
  собратьСущности('смена', camp.смены, s => ({ ...s, год: camp.год, дата: s.даты.подпись }));
  собратьСущности('пост', blog, п => ({ ...п }));

  const СПРАВОЧНИКИ = { courses, events, camp: camp.смены, blog,
    team: catalog.team, faq: catalog.faq,
    services: catalog.services, universities: catalog.universities };

  for (const [путь, оп] of Object.entries(structure.pages)) {
    if (путь.startsWith('$')) continue;
    const ctx = { ...контекст({ id: '' }, {}, путь),
      выборка: б => {
        const список = СПРАВОЧНИКИ[б.источник];
        if (!список) throw new Error(`неизвестный источник «${б.источник}» на ${путь}`);
        if (!б.фильтр) return список;
        const прошедшее = x => прошло((x.дата || x.даты).по, TODAY);
        if (б.фильтр === 'прошедшие') return список.filter(прошедшее);
        if (б.фильтр === 'предстоящие') return список.filter(x => !прошедшее(x));
        throw new Error(`неизвестный фильтр «${б.фильтр}» на ${путь}`);
      },
      оценка: () => site.отзывы, контакты: () => site.контакты,
      баннер: оп => {
        if (!оп || оп.источник === 'нет') return null;
        let сущ = null, папка = null;
        if (оп.источник === 'ближайшее') {
          const все = [...events.map(x => ({ x, п: 'events', д: x.дата.по })),
                       ...camp.смены.map(x => ({ x, п: 'camp', д: x.даты.по }))]
            .filter(v => v.д >= TODAY).sort((a, b) => a.д.localeCompare(b.д));
          if (!все.length) return оп.заголовок ? оп : null;
          сущ = все[0].x; папка = все[0].п;
        } else if (оп.источник) {
          папка = оп.источник;
          сущ = (СПРАВОЧНИКИ[оп.источник] || []).find(x => x.id === оп.id);
          if (!сущ) замечания.push(`баннер: в справочнике «${оп.источник}» нет «${оп.id}»`);
        }
        const подпись = сущ && сущ.описание
          ? `${сущ.описание}<br>${сущ.место || ''}` : (сущ ? сущ.место || '' : '');
        const из = сущ ? {
          заголовок: сущ.название, дата: (сущ.дата || сущ.даты).подпись,
          подпись, ссылка: `${папка}/${сущ.id}/index.html`,
        } : {};
        const итог = { ...из, ...Object.fromEntries(Object.entries(оп).filter(([k, v]) =>
          v != null && !['источник', 'id'].includes(k))) };
        if (сущ && прошло((сущ.дата || сущ.даты).по, TODAY))
          замечания.push(`баннер указывает на «${сущ.название}» — оно прошло ${(сущ.дата || сущ.даты).подпись}`);
        return итог.заголовок ? итог : null;
      },
      расписание: () => courses.flatMap(c => c.занятия.map(з => ({
        day: з.день, time: з.время, course: c.название, age: з.возраст,
        direction: c.направление, hall: з.зал, curator: c.куратор }))),
      кадры: б => (б.источник === 'site.галерея' ? site.галерея : [])
        .map(к => ({ ...к, ...(размеры[к.основа] || { ширина: 400, высота: 600 }) })),
      форма: () => форма('contacts', structure.form.поля) };
    const з = оп.заголовок;
    const шапкаСтраницы = з
      ? заголовокРаздела({ ...з, поля: з.поля || [], кнопка: !!з.кнопка,
          дополнительно: (з.дополнительно || []).map(б => НАПОЛНЕНИЯ[б.тип](б, ctx)).join('\n'),
          галереяHtml: '' })
      : null;
    let тело = [
      ...(шапкаСтраницы ? [шапкаСтраницы] : []),
      ...оп.блоки.map((б, i) => (шапкаСтраницы || i ? '\n' : '') + собратьЭлемент(б, ctx)),
    ].join('\n');
    if (оп.обёртка) тело = `  <div class="${оп.обёртка}">\n${тело}\n  </div>`;
    собрано.push([путь, страница({ site, структура, путь, тело, title: оп.title, description: оп.description,
      активный: оп.активный || путь, крошки: оп.крошки })]);
  }

  const т = данные.typography || {};
  const правила = т.включено ? (т.правила || []) : [];
  return { страницы: собрано.map(([п, html]) => [п, типографика(html, правила)]), замечания };
}
